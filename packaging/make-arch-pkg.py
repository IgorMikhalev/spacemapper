"""Pack a staged /usr tree into an Arch Linux package (.pkg.tar.zst).

This produces the same layout as makepkg (.PKGINFO, .MTREE, files) so release
packages can be built on any Linux system. On Arch itself you can simply use
packaging/arch/PKGBUILD with makepkg instead.

Usage: make-arch-pkg.py STAGE_DIR VERSION OUTPUT
"""
import gzip
import hashlib
import io
import os
import sys
import tarfile
import time

import zstandard

stage, version, out = sys.argv[1], sys.argv[2], sys.argv[3]
now = int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))

files, dirs = {}, set()
for root, dnames, fnames in os.walk(os.path.join(stage, "usr")):
    rel_root = os.path.relpath(root, stage)
    dirs.add(rel_root)
    for f in fnames:
        full = os.path.join(root, f)
        files[os.path.join(rel_root, f)] = (open(full, "rb").read(), os.stat(full).st_mode & 0o777)
dirs = sorted(dirs)
size = sum(len(b) for b, _ in files.values())

pkginfo = f"""# Generated by make-arch-pkg.py
pkgname = spacemapper
pkgbase = spacemapper
xdata = pkgtype=pkg
pkgver = {version}-1
pkgdesc = Treemap disk usage viewer
url = https://github.com/Martin-ii/spacemapper
builddate = {now}
packager = Martin Fleisch
size = {size}
arch = x86_64
license = GPL-3.0-or-later
depend = glibc
depend = libglvnd
depend = libxkbcommon
depend = wayland
depend = hicolor-icon-theme
optdepend = polkit: full access scans
optdepend = xdg-utils: open files and folders
optdepend = libxkbcommon-x11: X11 support
optdepend = libxcursor: X11 support
optdepend = libxi: X11 support
""".encode()


def digests(b):
    return f"md5digest={hashlib.md5(b).hexdigest()} sha256digest={hashlib.sha256(b).hexdigest()}"


mtree = ["#mtree", "/set type=file uid=0 gid=0 mode=644"]
mtree.append(f"./.PKGINFO time={now}.0 size={len(pkginfo)} {digests(pkginfo)}")
for d in dirs:
    mtree.append(f"./{d} time={now}.0 mode=755 type=dir")
for p in sorted(files):
    data, mode = files[p]
    m = "" if mode == 0o644 else f" mode={mode:o}"
    mtree.append(f"./{p} time={now}.0{m} size={len(data)} {digests(data)}")
mtree_gz = gzip.compress(("\n".join(mtree) + "\n").encode(), mtime=now)


def info(name, n, mode, typ=tarfile.REGTYPE):
    ti = tarfile.TarInfo(name)
    ti.size, ti.mode, ti.mtime, ti.type = n, mode, now, typ
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = "root"
    return ti


raw = io.BytesIO()
with tarfile.open(fileobj=raw, mode="w", format=tarfile.GNU_FORMAT) as t:
    t.addfile(info(".PKGINFO", len(pkginfo), 0o644), io.BytesIO(pkginfo))
    t.addfile(info(".MTREE", len(mtree_gz), 0o644), io.BytesIO(mtree_gz))
    for d in dirs:
        t.addfile(info(d, 0, 0o755, tarfile.DIRTYPE))
    for p in sorted(files):
        data, mode = files[p]
        t.addfile(info(p, len(data), mode), io.BytesIO(data))

with open(out, "wb") as f:
    f.write(zstandard.ZstdCompressor(level=19).compress(raw.getvalue()))
